def week(days, ganji, note):
    rows = ''.join(f'<tr><th style="text-align:left;width:120px">{d}</th><td style="font-size:56px;width:auto;text-align:left;padding:2px 0">'
                   f'<span style="{tc(GAN_E[g[0]])}">{g[0]}</span>{g[1]}</td></tr>' for d, g in zip(days, ganji))
    els = []
    for g in ganji:
        e = GAN_E[g[0]]
        if not els or els[-1] != e: els.append(e)
    flow = ' → '.join(E(e) for e in els)
    return ('<div class="step">이번 주 일진</div><div class="rule" style="margin:28px 0"></div>'
            f'<table style="margin:0">{rows}</table>'
            f'<p style="font-size:38px;line-height:1.6;margin-top:28px">천간이 {flow} 순서로 흘러요.</p>'
            f'<p {SM}>{note}</p>', "")

