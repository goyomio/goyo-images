def txt(step, *parts):
    out = f'<div class="step">{step}</div><div class="rule"></div>'
    for p in parts:
        if p.startswith('#'): out += f'<h2 style="font-size:60px;line-height:1.55">{p[1:]}</h2><br>'
        elif p.startswith('~'): out += f'<p {SM}>{p[1:]}</p>'
        else: out += f'<p {P}>{p}</p><br>'
    return (out, "")

